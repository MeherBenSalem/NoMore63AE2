#!/usr/bin/env python3
"""Generates docs/BOOK_FORMAT.md from the property declarations in the Java sources and the English tooltips.

Every quest object declares its fields in defineProps(); this script reads those calls so the reference can never
drift from the code. Run from the repository root:  python3 tools/gen_book_docs.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "1.21.1/common/src/main/java/dev/nightbeam/corerpg/quests"
LANG = json.loads((ROOT / "1.21.1/common/src/main/resources/assets/corerpg_quests/lang/en_us.json").read_text())

CALL = re.compile(r'p\.(string|text|stringList|idList|id|bool|integer|longValue|decimal|color|enumValue|resource|ref|item|items|icon|filter)\("([a-z_]+)"(.*?)\);', re.S)
CATEGORY = re.compile(r'p\.category\("([a-z_]+)"\)')

TYPE_NAMES = {
    "string": "text", "text": "text lines", "stringList": "list of text", "idList": "list of ids", "id": "id",
    "bool": "true/false", "integer": "integer", "longValue": "integer", "decimal": "number", "color": "colour (#RRGGBB)",
    "enumValue": "one of", "resource": "id", "ref": "id or #tag", "item": "item", "items": "list of items",
    "icon": "icon", "filter": "filter expression",
}


def props(path):
    text = path.read_text()
    starts = [i for i in (text.find("defineProps"), text.find("defineTaskProps")) if i >= 0]
    body = text[min(starts):] if starts else ""
    out = []
    category = "general"
    pos = 0
    events = sorted([(m.start(), "cat", m) for m in CATEGORY.finditer(body)] + [(m.start(), "prop", m) for m in CALL.finditer(body)], key=lambda e: e[0])
    for _, kind, m in events:
        if kind == "cat":
            category = m.group(1)
            continue
        fn, key, rest = m.group(1), m.group(2), m.group(3)
        default = ""
        args = [a.strip() for a in rest.split(",")]
        if fn in ("string", "bool", "color") and len(args) > 1:
            default = args[1]
        elif fn in ("integer", "longValue", "decimal") and len(args) > 3:
            hi = "no limit" if "MAX_VALUE" in args[3] else args[3]
            lo = args[2]
            default = f"{args[1]} (min {lo})" if hi == "no limit" else f"{args[1]} ({lo} to {hi})"
        elif fn == "enumValue" and len(args) > 2:
            enum = args[1].replace(".class", "")
            default = args[2].split(".")[-1].lower()
            fn_desc = f"{enum}"
            out.append((category, key, f"one of {enum}", default))
            continue
        out.append((category, key, TYPE_NAMES.get(fn, fn), default.replace('"', '`') if default else ""))
    return out


def tooltip(key):
    return LANG.get(f"corerpg_quests.prop.{key}.tooltip", "")


def section(title, files, note=""):
    lines = [f"### {title}", ""]
    if note:
        lines += [note, ""]
    seen = set()
    rows = []
    for f in files:
        for cat, key, typ, default in props(f):
            if key in seen:
                continue
            seen.add(key)
            rows.append((cat, key, typ, default))
    lines.append("| Key | Type | Default | Meaning |")
    lines.append("|---|---|---|---|")
    for cat, key, typ, default in rows:
        lines.append(f"| `{key}` | {typ} | {default or '—'} | {tooltip(key)} |")
    lines.append("")
    return lines


def main():
    base_obj = SRC / "book/QuestObject.java"
    out = [
        "# Quest book file format",
        "",
        "_Generated by `tools/gen_book_docs.py` from the mod's source. Do not edit by hand._",
        "",
        "The quest book lives in `config/corerpg_quests/book/`:",
        "",
        "```",
        "book/book.json                 book settings, chapter groups, chapter order",
        "book/chapters/<id>.json        one chapter: its settings, quests, links and images",
        "book/reward_tables/<id>.json   one reward table",
        "```",
        "",
        "Every object has an `id` (lower case, 1-64 characters of `a-z 0-9 _ - . /`, unique in the whole book).",
        "Only values that differ from the default are written. Text supports `&` colour codes and a `lang:` prefix for",
        "translation keys. Items are an id (`\"minecraft:diamond\"`) or the vanilla item stack object",
        "(`{\"id\": ..., \"count\": ..., \"components\": {...}}`). Icons are an item or `{\"texture\": \"ns:path.png\"}`.",
        "Tasks and rewards have a `type` (`item`, `kill`, ... or `namespace:path` for addon types).",
        "",
        "## Common fields (every object)",
        "",
    ]
    out += section("All objects", [base_obj])[2:]
    out += ["## Book (`book.json`)", ""] + section("Book settings", [SRC / "book/QuestBook.java"])[2:]
    out += section("Chapter group (in `book.json` → `groups`)", [SRC / "book/ChapterGroup.java"])
    out += section("Chapter", [SRC / "book/Chapter.java"], "A chapter file also holds `quests`, `links` and `images` arrays.")
    out += section("Quest", [SRC / "book/Quest.java"], "A quest also holds `tasks` and `rewards` arrays.")
    out += section("Quest link", [SRC / "book/QuestLink.java"])
    out += section("Chapter image", [SRC / "book/ChapterImage.java"])
    out += section("Reward table", [SRC / "book/RewardTable.java"], "A table also holds `entries`: rewards with an extra `weight`.")
    out += ["## Tasks", ""]
    out += section("Every task", [SRC / "task/Task.java"])
    task_types = re.findall(r'register\("([a-z_]+)", ([A-Za-z]+)(?:::new|::[a-z]+)', (SRC / "task/TaskTypes.java").read_text())
    for type_id, cls in task_types:
        if type_id == "unknown":
            continue
        files = [SRC / f"task/types/{cls}.java"]
        parent = re.search(r"extends (\w+)", files[0].read_text())
        if parent and (SRC / f"task/types/{parent.group(1)}.java").exists():
            files.insert(0, SRC / f"task/types/{parent.group(1)}.java")
            grand = re.search(r"extends (\w+)", files[0].read_text())
            if grand and (SRC / f"task/types/{grand.group(1)}.java").exists():
                files.insert(0, SRC / f"task/types/{grand.group(1)}.java")
        name = LANG.get(f"corerpg_quests.task_type.corerpg_quests.{type_id}", type_id)
        out += section(f"`{type_id}` — {name}", files)
    out += ["## Rewards", ""]
    out += section("Every reward", [SRC / "reward/Reward.java"])
    reward_types = re.findall(r'register\("([a-z_]+)", ([A-Za-z]+)(?:::new|::[a-z]+)', (SRC / "reward/RewardTypes.java").read_text())
    for type_id, cls in reward_types:
        if type_id == "unknown":
            continue
        name = LANG.get(f"corerpg_quests.reward_type.corerpg_quests.{type_id}", type_id)
        block = section(f"`{type_id}` — {name}", [SRC / f"reward/types/{cls}.java"])
        # XpReward picks its key at runtime ("xp" or "levels"), which the regex cannot see.
        if type_id in ("xp", "xp_levels"):
            key, default = ("xp", 100) if type_id == "xp" else ("levels", 5)
            block.insert(-1, f"| `{key}` | integer | {default} (1 to 1_000_000_000) | {tooltip(key)} |")
        out += block
    (ROOT / "docs/BOOK_FORMAT.md").write_text("\n".join(out) + "\n")
    print("wrote docs/BOOK_FORMAT.md")


if __name__ == "__main__":
    main()
