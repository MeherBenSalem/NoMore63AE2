package dev.nightbeam.corerpg.quests.mixin;

import dev.nightbeam.corerpg.quests.server.CommonEvents;
import dev.nightbeam.corerpg.quests.task.TriggerEvent;
import net.minecraft.advancements.critereon.ConsumeItemTrigger;
import net.minecraft.server.level.ServerPlayer;
import net.minecraft.world.item.ItemStack;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

@Mixin(ConsumeItemTrigger.class)
public abstract class ConsumeItemTriggerMixin {
    @Inject(method = "trigger", at = @At("HEAD"))
    private void corerpg$onConsume(ServerPlayer player, ItemStack stack, CallbackInfo ci) {
        CommonEvents.trigger(player, new TriggerEvent.Consume(stack.copy()));
    }
}
